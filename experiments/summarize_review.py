"""Audit frozen pilot measurements and regenerate manuscript tables and figure."""
from pathlib import Path
import argparse, collections, hashlib, json, statistics
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT=Path(__file__).resolve().parent.parent
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--results',type=Path,default=ROOT/'experiments/results/review_revision')
parser.add_argument('--figure',type=Path,default=ROOT/'figures/evaluation_runtime.pdf')
args=parser.parse_args()
OUT=args.results
args.figure.parent.mkdir(parents=True,exist_ok=True)
rows=[json.loads(line) for line in (OUT/'measurements.jsonl').read_text().splitlines()]
env=json.loads((OUT/'environment.json').read_text())
assert len(rows)==180 and all(r['feasible'] for r in rows)
assert env['script_sha256']==hashlib.sha256((ROOT/'experiments/review_revision.py').read_bytes()).hexdigest()
groups=collections.defaultdict(list)
for r in rows:groups[r['sf'],r['kind'],r['fraction'],r['method']].append(r)
assert len(groups)==60 and all(len(rr)==3 for rr in groups.values())
for key,rr in groups.items():
 assert {r['repetition'] for r in rr}=={1,2,3}
 opt=groups[key[:3]+('ilp',)]
 assert all(r['status']=='optimal' for r in opt)
 assert len({r['size'] for r in rr+opt})==1

def median(sf,kind,a,method):return statistics.median(r['runtime_s'] for r in groups[sf,kind,a,method])
summary={'runs':len(rows),'cases':18,'optimal_ilp_runs':54,'feasible_runs':180,'timeouts':0,
         'exact_greedy_cases':12,'avg_heuristic_cases':6,'all_match_optimum':True,
         'timing_repetitions':3,'summary':[]}
for (sf,kind,a,method),rr in sorted(groups.items()):
 summary['summary'].append({'sf':sf,'kind':kind,'fraction':a,'method':method,'size':rr[0]['size'],
          'median_s':statistics.median(r['runtime_s'] for r in rr),'min_s':min(r['runtime_s'] for r in rr),'max_s':max(r['runtime_s'] for r in rr)})
(OUT/'summary.json').write_text(json.dumps(summary,indent=2)+'\n')
colors={'ilp':'#303d53','incremental':'#157a6e','circuit':'#4378bf','lazy_sql':'#c46e24','avg_heuristic':'#8e4f94'}
labels={'ilp':'Full ILP','incremental':'Incremental','circuit':'Circuit pass','lazy_sql':'Lazy SQL','avg_heuristic':'AVG heuristic'}
plt.rcParams.update({'font.size':8,'pdf.fonttype':42,'ps.fonttype':42,'axes.spines.top':False,'axes.spines.right':False})
fig,axs=plt.subplots(1,3,figsize=(7,2.15),layout='constrained')
for ax,kind in zip(axs,('COUNT','SUM','AVG')):
 fractions=['0.10','0.25','0.50'] if kind!='AVG' else ['0.02','0.05','0.10']
 methods=['ilp','incremental','circuit','lazy_sql'] if kind!='AVG' else ['ilp','avg_heuristic']
 for method in methods:
  rr=[groups['0.03',kind,a,method] for a in fractions]
  med=[statistics.median(r['runtime_s'] for r in group)*1000 for group in rr]
  low=[min(r['runtime_s'] for r in group)*1000 for group in rr];high=[max(r['runtime_s'] for r in group)*1000 for group in rr]
  ax.plot([float(a)*100 for a in fractions],med,marker='o',markersize=3,color=colors[method],label=labels[method])
  ax.fill_between([float(a)*100 for a in fractions],low,high,color=colors[method],alpha=.12)
 ax.set(title=kind,xlabel='Requested decrease (%)',yscale='log')
 ax.set_xticks([float(a)*100 for a in fractions]);ax.grid(axis='y',which='major',alpha=.18)
 ax.legend(fontsize=6,frameon=False,loc='best')
axs[0].set_ylabel('Setup + optimization (ms)')
fig.savefig(args.figure)
fig.savefig(ROOT/'build/evaluation_runtime.png',dpi=200)
plt.close(fig)
lines=[r'% Generated by experiments/summarize_review.py from frozen measurements.',r'\begin{table}[t]',r'\centering',r'\caption{Optimal witness sizes in the TPC-H-derived pilot. Every measured greedy variant attained these sizes; each case has three timing repetitions.}',r'\label{tab:pilot-sizes}',r'\small',r'\begin{tabular}{@{}lrrr@{}}',r'\toprule',r'Aggregate & Decrease (\%) & SF 0.01 & SF 0.03\\',r'\midrule']
for kind in ('COUNT','SUM','AVG'):
 for a in (['0.10','0.25','0.50'] if kind!='AVG' else ['0.02','0.05','0.10']):
  sizes=[groups[sf,kind,a,'ilp'][0]['size'] for sf in ('0.01','0.03')]
  lines.append(r'\agg{'+kind+'} & '+str(round(float(a)*100))+' & '+str(sizes[0])+' & '+str(sizes[1])+r'\\')
lines.extend([r'\bottomrule',r'\end{tabular}',r'\end{table}'])
(OUT/'sizes.tex').write_text('\n'.join(lines)+'\n')
print('Audited 180 measurements, 60 complete timing groups, and 18 proven-optimum cases.')
print('SF .03, 50% COUNT speedup, ILP / incremental:',median('0.03','COUNT','0.50','ilp')/median('0.03','COUNT','0.50','incremental'))
print('SF .03, AVG 10% heuristic / ILP:',median('0.03','AVG','0.10','avg_heuristic')/median('0.03','AVG','0.10','ilp'))
